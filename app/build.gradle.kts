class RobolectricDepsArgProvider(
  @get:InputFiles
  @get:PathSensitive(PathSensitivity.NONE)
  val sdkFiles: FileCollection,
  @get:Internal
  val depsFile: Provider<RegularFile>,
) : CommandLineArgumentProvider {
  override fun asArguments(): Iterable<String> {
    val sdkJar = sdkFiles.files.firstOrNull { it.extension == "jar" } ?: return emptyList()
    val outputFile = depsFile.get().asFile
    outputFile.parentFile?.mkdirs()
    val props = Properties().apply {
      setProperty("org.robolectric:android-all-instrumented:16-robolectric-13921718-i7", sdkJar.absolutePath)
    }
    outputFile.outputStream().use { out ->
      props.store(out, "Generated by Gradle for deterministic Robolectric SDK resolution")
    }
    return listOf("-Drobolectric-deps.properties=${outputFile.absolutePath}")
  }
}

